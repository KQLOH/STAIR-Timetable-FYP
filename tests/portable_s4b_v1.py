"""portable-s4b-v1: invented in-memory test inputs; no historical resource or server.

PDF bytes/specification are reproducible. Canonical UUIDs and credentials are
fresh per test instance, then bound to that instance's exact input digests.
This is not a replacement for the retained S4B acceptance evidence/approval.
"""
from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = 'http://127.0.0.1:8017'  # Existing transport's exact origin; no listener.
VERSION = 'portable-s4b-v1'
TARGET = 'test:portable-s4b-v1-isolated'
REVIEW_ACTOR = 'PORTABLE-SYNTHETIC-REVIEWER-v1'
REVIEW_PERMISSIONS = frozenset({'read', 'queue', 'assign', 'correct', 'revalidate', 'oversee'})
CALENDAR_PERMISSIONS = frozenset({'read', 'preview', 'approve', 'execute', 'reconcile'})
MANIFEST = ROOT / 'tests/portable_s4b_manifest_v1.json'
MANIFEST_SHA256 = 'da8f4725ff5012860ecc65473ea77785f7f59ee1de2322451d8c3dc32da49566'
RESOURCE_PATHS = frozenset({
    'tests/portable_s4b_spec_v1.json', 'tests/s4b_transport.py',
    'tests/s4b_host_bootstrap.js', 'tests/s4b_transport_checks.js',
})


def _pdf(spec):
    from reportlab.pdfgen.canvas import Canvas
    output = BytesIO()
    # invariant strips wall-clock/random metadata; no local font or file inputs.
    canvas = Canvas(output, pagesize=tuple(spec['review']['page_size']), invariant=1)
    canvas.setTitle('Independent portable synthetic timetable v1')
    canvas.setAuthor('Synthetic test generator')
    canvas.setFont('Helvetica', 16)
    for index, line in enumerate(spec['review']['lines']):
        canvas.drawString(20, 240 - index * 60, line)
    canvas.save()
    raw = output.getvalue()
    # Preserve the unchanged transport's exact 1533-byte wire contract. PDF
    # permits trailing whitespace; the independently generated bytes stay pinned.
    if len(raw) > 1533:
        raise RuntimeError('PORTABLE_PDF_WIRE_SIZE_UNSUPPORTED')
    return raw + b' ' * (1533 - len(raw))


def verify_approved_inputs():
    """Name retained for existing assertions; pins a NEW test-resource version.

    Hash validity grants neither historical approval nor live enrollment rights.
    """
    raw = MANIFEST.read_bytes()
    if sha256(raw).hexdigest() != MANIFEST_SHA256:
        raise RuntimeError('PORTABLE_MANIFEST_DRIFT')
    manifest = json.loads(raw)
    if manifest.get('version') != VERSION or set(manifest.get('files', {})) != RESOURCE_PATHS:
        raise RuntimeError('PORTABLE_MANIFEST_INVALID')
    for name, expected in manifest['files'].items():
        if sha256((ROOT / name).read_bytes()).hexdigest() != expected:
            raise RuntimeError('PORTABLE_RESOURCE_DRIFT')
    spec = json.loads((ROOT / 'tests/portable_s4b_spec_v1.json').read_bytes())
    if spec.get('version') != VERSION or spec['review']['event_count'] != 2:
        raise RuntimeError('PORTABLE_SPEC_INVALID')
    if sha256(_pdf(spec)).hexdigest() != manifest['review']['pdf_sha256']:
        raise RuntimeError('PORTABLE_PDF_DRIFT')
    return manifest


def review_pdf():
    verify_approved_inputs()
    return _pdf(json.loads((ROOT / 'tests/portable_s4b_spec_v1.json').read_bytes()))


def review_assessment(application):
    """Return the exact host-instance source, detached; never a fresh identity."""
    return application.state.portable_review_request.model_dump(mode='json')


def build_host(directory, target, *, audit=None):
    """Only isolated TestClient setup. No serve(), console runner or HTTP issuer."""
    directory = Path(directory).resolve()
    if target != TARGET or not directory.is_relative_to(ROOT / 'data/temp'):
        raise ValueError('PORTABLE_TEST_TARGET_REQUIRED')
    if directory.exists():
        raise ValueError('PORTABLE_FRESH_DIRECTORY_REQUIRED')
    manifest = verify_approved_inputs()
    spec = json.loads((ROOT / 'tests/portable_s4b_spec_v1.json').read_bytes())
    from fastapi import FastAPI
    from backend import main
    from backend.review.auth import TrustedHostAuthority
    from backend.review.store import ReviewStore
    from backend.review.api import ReviewBridge
    from backend.review.binding import AssessmentInput
    from backend.services.file_extractor import extract_document
    from backend.services.extraction_adapter import adapt_extraction
    from backend.reconstruction.service import reconstruct
    from backend.reconstruction.models import digest
    from backend.calendar.access import CalendarAccess
    from backend.calendar.sandbox import LocalSandbox
    from backend.calendar.testing import SyntheticFixtureAuthority
    from backend.calendar.workflow import TestOnlyCalendarBridge
    from backend.calendar.models import CalendarError
    from tests.s4b_transport import Broker, Capability, TransportMiddleware

    packet = adapt_extraction(extract_document('portable-review.pdf', 'application/pdf', _pdf(spec)))
    request = AssessmentInput(source_packet=packet, reconstruction=reconstruct(packet, 'constrained'))
    binding = {(packet.source.source_document_id, packet.source.content_sha256)}
    review_authority = TrustedHostAuthority(test_only_source_bindings=binding)
    initial = TrustedHostAuthority()
    sandbox = LocalSandbox(directory, target, CalendarAccess(initial), test_only=True)
    generator = SyntheticFixtureAuthority(sandbox)
    values = spec['calendar']
    base = generator.make(events=values['events'], capture_id=values['capture_id'])
    update = generator.make(previous=base, changes=values['update'])
    failure = generator.make(previous=update, changes=values['failure'])
    blocked = generator.make(previous=base, changes=values['blocked'])
    catalogue = {'base-v1': base, 'update-v2': update, 'failure-v3': failure, 'blocked-v4': blocked}
    frozen_digests = {key: digest(bundle.model_dump(mode='json')) for key, bundle in catalogue.items()}
    source = base.packet.source
    bindings = {(source.source_document_id, source.content_sha256)}
    calendar_authority = TrustedHostAuthority(test_only_source_bindings=bindings)
    reviewer, review_token = review_authority.issue(REVIEW_ACTOR, REVIEW_PERMISSIONS,
        mode='TEST_ONLY', source_bindings=binding, lifetime_minutes=30)
    try:
        owner, calendar_token = calendar_authority.issue('PORTABLE-SYNTHETIC-OWNER-v1', {'read'},
            mode='TEST_ONLY', source_bindings=bindings, lifetime_minutes=30)
        access = CalendarAccess(calendar_authority)
        access.enrol(owner, target, CALENDAR_PERMISSIONS)
        sandbox.access = access

        class PortableCalendarBridge(TestOnlyCalendarBridge):
            def execute(self, approval_id, actor, scenario='NONE', replay_only=False):
                if scenario != 'NONE' and self.approval_plan(approval_id, actor, 'execute').input_digest != frozen_digests['failure-v3']:
                    raise CalendarError('S4B_FAILURE_FIXTURE_REQUIRED', 403)
                return super().execute(approval_id, actor, scenario, replay_only)

        store = ReviewStore(review_authority)
        store.ingest(request, reviewer)
        app = FastAPI(debug=False)
        app.include_router(main.app.router)
        app.state.m5_review_bridge = ReviewBridge(store, (ORIGIN,))
        app.state.s3c_calendar_bridge = PortableCalendarBridge(sandbox,
            {key: (VERSION + ': ' + key, bundle) for key, bundle in catalogue.items()},
            allowed_origins=(ORIGIN,), allow_failure_simulation=True)
        app.state.portable_review_request = request
        broker = Broker({'review': Capability(review_authority, reviewer, review_token),
                         'calendar': Capability(calendar_authority, owner, calendar_token)}, audit=audit)
        app.add_middleware(TransportMiddleware, broker=broker,
                          approved_pdf_sha=manifest['review']['pdf_sha256'])
        return app, broker
    except Exception:
        review_authority.revoke(reviewer)
        if 'owner' in locals():
            calendar_authority.revoke(owner)
        raise
